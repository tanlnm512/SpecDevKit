#!/usr/bin/env bash
# Sync every skill in this repo (master source) to every install root,
# then SHA-verify the result.
#
# Topology — N skills (skills/<name>/) x the harness roots below:
#   skills/<name>/            -> ~/.agents/skills/<name>/
#                              -> ~/.claude/skills/<name>/
#                              -> ~/.zcode/skills/<name>/
#                              -> ~/.omp/agent/skills/<name>/
#                                 (omp-native root, priority-100 provider
#                                 — omp sessions load this copy)
#   skills/<name>/commands/<name>.md -> ~/.agents/commands/,
#                              ~/.claude/commands/, ~/.zcode/commands/
#                              — plus the bare names the skill opts into
#                              via its own commands/extra.txt (generic
#                              names in shared roots are an explicit
#                              per-skill opt-in, never a glob; a foreign
#                              file at any destination is refused, not
#                              clobbered — except at the flat command
#                              roots, where a name no skill claims
#                              anymore is pruned when the ledger proves
#                              it was our deploy, left alone otherwise;
#                              omp needs none —
#                              /skill:<name> auto-registers)
#                              — ~/.factory/commands/ too, gated on
#                              ~/.factory existing (Factory Droid's
#                              own command root; never fabricated,
#                              loud skip otherwise)
#                              — ~/.config/kilo/command/ too, gated on
#                              ~/.config/kilo existing (Kilo CLI's
#                              global config dir; same never-fabricate
#                              rule; Kilo reads commands from
#                              {command,commands}/*.md there)
#   skills/<name>/agents/*.md -> ~/.claude/agents/ (as-is; the harness
#                                 reads Claude-style frontmatter directly)
#                              -> ~/.omp/agent/agents/ (regenerated with
#                                 omp frontmatter by tools/omp-defs.py —
#                                 omp skips ~/.claude/agents and its tool
#                                 registry is lowercase). Files named with
#                                 a leading underscore (shared prose, e.g.
#                                 _shared-protocol.md) are not roles and
#                                 are skipped. zcode gets no agents/
#                                 install step: SKILL.md § Spawn mechanics
#                                 documents it as having no
#                                 user-installable agent types, so it
#                                 only gets skills/ + commands/.
#                              -> ~/.config/opencode/agents/ and
#                                 ~/.factory/droids/ (OPTIONAL roots,
#                                 regenerated by tools/agent-defs.py:
#                                 opencode subagents / Factory droids).
#                                 Installed only when the harness's own
#                                 config home exists — sync never
#                                 fabricates a harness directory. Both
#                                 harnesses read skills from the
#                                 ~/.agents/skills compatibility root
#                                 already installed above.
#                              -> ~/.config/kilo/skills/<name>/ too
#                                 (OPTIONAL root, gated on ~/.config/kilo
#                                 existing — Kilo's native skills scan
#                                 surface; the ~/.agents compatibility
#                                 copy above still feeds every harness
#                                 that reads it).
#                              -> ~/.config/kilo/agent/ (OPTIONAL root,
#                                 regenerated by tools/agent-defs.py
#                                 --target kilo: Kilo CLI subagents —
#                                 description + mode: subagent + a
#                                 permission map derived from each
#                                 brief's own tools:, task always
#                                 denied). Same config-home gate; Kilo
#                                 reads skills from the ~/.agents/skills
#                                 compatibility root natively, so no
#                                 skills copy is added for it.
#                              -> <repo>/agents/ (agy personas — COMMITTED
#                                 regenerate-only copies of the briefs:
#                                 the repo root is the plugin that
#                                 `agy plugin install` copies; agy owns
#                                 ~/.gemini/config/plugins itself).
#   rules/engineering-rules.md -> the § Engineering rules sections in
#                              skills/spec-execute/agents/builder.md
#                              and skills/spec-code-review/agents/
#                              code-review-fixer.md — COMMITTED
#                              regenerate-only carrier views, refreshed
#                              in-place by tools/kit-rules.py before
#                              install and drift-checked in verify
#                              (D-028). Repo-local: nothing here is
#                              installed to a harness root.
#
# omp also reads ~/.agents/skills (its `agents` provider, priority 70),
# so that root alone would serve omp sessions; the ~/.omp copy makes
# every skill self-sufficient inside omp and wins omp's same-name dedup.
#
# A skill opts into this topology just by existing at skills/<name>/ with
# a SKILL.md — no registration step, no list to edit here.
#
# Run from anywhere: tools/sync.sh — edits always land in skills/<name>/
# first; this script is the only thing that copies out.
#
# Modes (FR-009): plain `tools/sync.sh` applies the plan (pruning
# stale flat-root command deploys the ledger proves it owns, and
# sweeping the roots of skills named in tools/retired-skills.txt whose
# masters no longer ship — ledger-proven deploys deleted, foreign files
# refused); `--dry-run` prints the full plan — create/update/unchanged/
# delete/stale-delete/refuse per destination — and exits; `--check`
# reports refusals, stale command deploys (shipped names no skill
# claims anymore), plus drift between the masters and what is
# installed. Neither mode writes a destination or records ownership.
set -euo pipefail

PKG_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
fail=0

usage() {
  echo "usage: tools/sync.sh [--dry-run|--check]" >&2
}

DRY_RUN=0
CHECK=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    --check) CHECK=1 ;;
    *) echo "ERROR: unknown argument: $1" >&2; usage; exit 2 ;;
  esac
  shift
done
if [ "$DRY_RUN" = 1 ] && [ "$CHECK" = 1 ]; then
  echo "ERROR: --dry-run and --check are mutually exclusive" >&2
  usage
  exit 2
fi

SKILLS_ROOTS=(
  "$HOME/.agents/skills"
  "$HOME/.claude/skills"
  "$HOME/.zcode/skills"
  "$HOME/.omp/agent/skills"
)
COMMANDS_ROOTS=(
  "$HOME/.agents/commands"
  "$HOME/.claude/commands"
  "$HOME/.zcode/commands"
)
CLAUDE_AGENTS_ROOT="$HOME/.claude/agents"
OMP_AGENTS_ROOT="$HOME/.omp/agent/agents"
# Optional harness agent-def roots — active only when the harness's own
# config home exists (see the install loop).
OPENCODE_AGENTS_ROOT="$HOME/.config/opencode/agents"
DROID_AGENTS_ROOT="$HOME/.factory/droids"
DROID_COMMANDS_ROOT="$HOME/.factory/commands"
KILO_HOME="$HOME/.config/kilo"
KILO_COMMANDS_ROOT="$KILO_HOME/command"
KILO_AGENTS_ROOT="$KILO_HOME/agent"

# Bare-named commands a skill ships beyond its collision-proof
# <name>.md router: an explicit `commands/extra.txt` in the skill (one
# line, space-separated bare names — a reviewed file inside the skill
# dir, never a glob; ADR-013). Generic names (spec.md, plan.md, ...)
# land flat in shared global command roots, so the opt-in lives with
# the skill that pays for it, and a second skill wanting the same bare
# name is a rename-or-namespace decision.
extra_commands() {  # <skill-name> -> bare names on stdout
  local f="$PKG_ROOT/skills/$1/commands/extra.txt"
  if [ -f "$f" ]; then cat "$f"; fi
}

# Provenance ledger: every command root keeps the sha256 of each file
# this script deployed there (.spec-dev-kit-deployed — harnesses read
# only *.md, so the hidden file is inert). A destination that differs
# from the master is overwritten ONLY when its hash sits in the ledger
# (a previous deploy of ours, committed or not); anything else at the
# destination is foreign — refuse loudly, never clobber.
ledger_entry_matches() {  # <ledger-file> <command-name> <dest-file>
  [ -f "$1" ] || return 1
  local want
  want="$(shasum -a 256 < "$3" | cut -d' ' -f1)"
  awk -v n="$2" -v h="$want" '$1 == h && $2 == n {found = 1}
        END {exit found ? 0 : 1}' "$1"
}

ledger_record() {  # <ledger-file> <command-name> <master-file>
  local h
  h="$(shasum -a 256 < "$3" | cut -d' ' -f1)"
  # Rewrite via destination-local scratch renamed over the ledger, so
  # the ledger file itself never holds partial content (FR-007).
  if [ -f "$1" ]; then
    grep -v " $2\$" "$1" > "$1.tmp" || true
  else
    : > "$1.tmp"
  fi
  printf '%s %s\n' "$h" "$2" >> "$1.tmp"
  mv "$1.tmp" "$1"
}

ledger_forget() {  # <ledger-file> <command-name>
  [ -f "$1" ] || return 0
  grep -v " $2\$" "$1" > "$1.tmp" || true
  mv "$1.tmp" "$1"
}

sha() {  # <file> -> sha256 on stdout
  shasum -a 256 < "$1" | cut -d' ' -f1
}

LEDGER_NAME=".spec-dev-kit-deployed"

# Destination-local staging + atomic replacement (FR-007): content lands
# via rename from a scratch file in the destination's own directory, so
# a destination is never seen half-written. Scratch carries the
# LEDGER_NAME prefix — the installer-scratch namespace the sweep, the
# ledger rewrites, the verify pass, and tools/ownership.py's inventory
# all already exclude — so even a crash leftover can never be
# misclassified as a foreign file.
atomic_put() {  # <src> <dest>
  local tmp
  tmp="$(dirname "$2")/$LEDGER_NAME.tmp-$(basename "$2").tmp"
  rm -f "$tmp"
  cp -p "$1" "$tmp"
  mv "$tmp" "$2"
}

# Flat command roots are shared turf: a name this kit deployed that no
# skill claims anymore (no router, no extra.txt entry) is a stale
# deploy — pruned only while its hash still matches the ledger.
# Anything else at that name is foreign now and stays untouched, never
# refused: the name is no longer ours to defend.
claimed_command_names() {
  local name base
  for name in "${SKILLS[@]}"; do
    printf '%s\n' "$name"
    for base in $(extra_commands "$name"); do
      printf '%s\n' "$base"
    done
  done
}

stale_commands_in() {  # <root> — ledgered, unclaimed, hash-verified names
  local root="$1"
  local ledger="$root/$LEDGER_NAME" name claimed
  [ -f "$ledger" ] || return 0
  claimed="$(claimed_command_names | sort -u)"
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    [ -f "$root/$name.md" ] || continue
    printf '%s\n' "$claimed" | grep -qx "$name" && continue
    ledger_entry_matches "$ledger" "$name" "$root/$name.md" || continue
    printf '%s\n' "$name"
  done < <(awk '{print $2}' "$ledger")
}

plan_stale_commands() {  # <root> — dry-run's delete decisions
  local root="$1" name
  [ "$DRY_RUN" = 1 ] || return 0
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    echo "plan  delete $root/$name.md"
  done < <(stale_commands_in "$root")
}

prune_stale_commands() {  # <root>
  local root="$1" name names
  names="$(stale_commands_in "$root")"
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    rm "$root/$name.md"
    ledger_forget "$root/$LEDGER_NAME" "$name"
    echo "clean $root/$name.md (stale deploy)"
  done < <(stale_commands_in "$root")
}

check_stale_commands() {  # <root>
  local root="$1" name
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    echo "STALE $root/$name.md (deployed name no longer shipped — rerun sync)"
    fail=1
  done < <(stale_commands_in "$root")
}

# --- retired-skills sweep (D-007, FR-009) ----------------------------------
# tools/retired-skills.txt names skills this kit retired. Once the master
# skills/<name>/ is gone, the install roots still hold its deploys; the
# sweep removes exactly what the provenance ledgers prove this kit
# deployed there (skills-tree ledgers, the command roots' ledger, the
# omp per-skill manifest) and refuses everything else in those paths —
# retirement never deletes a foreign file. A name whose master still
# ships is skipped, so the list can land before the retirement delete
# and stays a no-op until then.

RETIRED_SKILLS_FILE="$PKG_ROOT/tools/retired-skills.txt"

retired_names() {  # candidates from the committed list, comments stripped
  [ -f "$RETIRED_SKILLS_FILE" ] || return 0
  sed -e 's/#.*//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' \
      -e '/^$/d' "$RETIRED_SKILLS_FILE"
}

sweep_retired_tree() {  # <dest-tree> — per file: ledger-proven deleted,
  #                      anything else in the retired skill's path refused
  local dest="$1" rel bad=0
  local ledger="$dest/$LEDGER_NAME"
  local stale=()
  [ -d "$dest" ] || return 0
  while IFS= read -r rel; do
    rel="${rel#./}"; [ -n "$rel" ] || continue
    if ledger_entry_matches "$ledger" "$rel" "$dest/$rel"; then
      stale+=("$rel")
    else
      echo "REFUSE $dest/$rel — foreign file in retired skill's tree (not a proven deploy); resolve manually"
      bad=1
    fi
  done < <(cd "$dest" && find . -type f ! -name '.DS_Store' \
      ! -path '*/__pycache__/*' ! -name "$LEDGER_NAME*")
  # bash 3.2 + set -u: expanding an empty array errors; guard the loop
  if [ "${#stale[@]}" -gt 0 ]; then
    for rel in "${stale[@]}"; do
      if [ "$DRY_RUN" = 1 ]; then
        echo "plan  delete $dest/$rel"
      elif [ "$CHECK" = 1 ]; then
        echo "STALE $dest/$rel (retired skill deploy — rerun sync)"
      else
        rm "$dest/$rel"
        echo "clean $dest/$rel (retired skill deploy)"
      fi
    done
  fi
  # The ledger and the emptied directories are the installer's own;
  # a tree that still holds a refused foreign file keeps them too.
  if [ "$bad" -eq 0 ] && [ "$DRY_RUN" = 0 ] && [ "$CHECK" = 0 ]; then
    rm -f "$dest/$LEDGER_NAME"
    find "$dest" -depth -type d -empty -delete
  fi
  return "$bad"
}

sweep_retired_command() {  # <root> <retired-name>
  local root="$1" name="$2" dest="$root/$name.md"
  [ -f "$dest" ] || return 0
  # A shipping skill claiming the bare name owns it now (the split's
  # thin alias does exactly that); an unclaimed foreign file at a flat
  # root is shared turf — neither is this sweep's to touch.
  if printf '%s\n' "$(claimed_command_names | sort -u)" \
      | grep -qx "$name"; then
    return 0
  fi
  ledger_entry_matches "$root/$LEDGER_NAME" "$name" "$dest" || return 0
  if [ "$DRY_RUN" = 1 ]; then
    echo "plan  delete $dest"
  elif [ "$CHECK" = 1 ]; then
    echo "STALE $dest (retired skill deploy — rerun sync)"
  else
    rm "$dest"
    ledger_forget "$root/$LEDGER_NAME" "$name"
    echo "clean $dest (retired skill deploy)"
  fi
  return 0
}

sweep_retired_omp_defs() {  # <retired-name> — the per-skill manifest is
  #                          the ledger in the shared omp agents root
  local name="$1"
  local manifest="$OMP_AGENTS_ROOT/.spec-dev-kit-omp-defs-$name"
  local rel dest bad=0
  local stale=()
  [ -f "$manifest" ] || return 0
  while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    dest="$OMP_AGENTS_ROOT/$rel"
    if [ ! -f "$dest" ]; then
      continue
    fi
    if ledger_entry_matches "$manifest" "$rel" "$dest"; then
      stale+=("$rel")
    else
      echo "REFUSE $dest — foreign file under retired skill's omp manifest (content drifted); resolve manually"
      bad=1
    fi
  done < <(awk '{print $2}' "$manifest")
  if [ "${#stale[@]}" -gt 0 ]; then
    for rel in "${stale[@]}"; do
      if [ "$DRY_RUN" = 1 ]; then
        echo "plan  delete $OMP_AGENTS_ROOT/$rel"
      elif [ "$CHECK" = 1 ]; then
        echo "STALE $OMP_AGENTS_ROOT/$rel (retired skill deploy — rerun sync)"
      else
        rm "$OMP_AGENTS_ROOT/$rel"
        echo "clean $OMP_AGENTS_ROOT/$rel (retired skill deploy)"
      fi
    done
  fi
  if [ "$bad" -eq 0 ] && [ "$DRY_RUN" = 0 ] && [ "$CHECK" = 0 ]; then
    rm -f "$manifest"
  fi
  return "$bad"
}

sweep_retired_skills() {
  local name root
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    if [ -d "$PKG_ROOT/skills/$name" ]; then
      echo "skip retired sweep for $name — master still ships; activate at its retirement"
      continue
    fi
    for root in "${SKILLS_ROOTS[@]}"; do
      sweep_retired_tree "$root/$name" || fail=1
    done
    if [ -d "$KILO_HOME" ]; then
      sweep_retired_tree "$KILO_HOME/skills/$name" || fail=1
    fi
    for root in "${COMMANDS_ROOTS[@]}"; do
      sweep_retired_command "$root" "$name"
    done
    if [ -d "$HOME/.factory" ]; then
      sweep_retired_command "$DROID_COMMANDS_ROOT" "$name"
    fi
    if [ -d "$KILO_HOME" ]; then
      sweep_retired_command "$KILO_COMMANDS_ROOT" "$name"
    fi
    sweep_retired_omp_defs "$name" || fail=1
  done < <(retired_names)
}


# Skills-tree provenance — the command roots' refuse-don't-clobber
# rule, applied to a whole installed directory. Every dest file is
# classified before anything is touched: a path the master still ships
# may be replaced only when identical or ledger-own (a previous deploy
# of ours); a path the master no longer ships is deleted only when its
# current hash is still the ledgered deployed hash; anything else is
# foreign — REFUSED loudly, and nothing in the tree is written or
# removed. Returns 1 when anything foreign was found.
sweep_tree() {  # <master-dir> <dest-dir> <ledger>
  local master="$1" dest="$2" ledger="$3" rel bad=0
  local stale=()
  [ -d "$dest" ] || return 0
  while IFS= read -r rel; do
    rel="${rel#./}"; [ -n "$rel" ] || continue
    if [ -f "$master/$rel" ]; then
      if cmp -s "$master/$rel" "$dest/$rel" \
         || ledger_entry_matches "$ledger" "$rel" "$dest/$rel"; then
        continue
      fi
      echo "REFUSE $dest/$rel — foreign file (differs from master, not a prior deploy); resolve manually"
      bad=1
    elif ledger_entry_matches "$ledger" "$rel" "$dest/$rel"; then
      stale+=("$rel")
    else
      echo "REFUSE $dest/$rel — foreign file (not shipped by the skill, not a prior deploy); resolve manually"
      bad=1
    fi
  done < <(cd "$dest" && find . -type f ! -name '.DS_Store' \
      ! -path '*/__pycache__/*' ! -name "$LEDGER_NAME*")
  [ "$bad" -eq 0 ] || return 1
  # bash 3.2 + set -u: expanding an empty array errors; guard the loop
  if [ "${#stale[@]}" -gt 0 ]; then
    for rel in "${stale[@]}"; do
      rm "$dest/$rel"
      echo "clean $dest/$rel (stale deploy)"
    done
  fi
  return 0
}

# Rebuild a tree's ledger from what is now installed — the deployed
# tree itself is the truth, so this is a full rewrite, not a merge.
record_tree() {  # <dest-dir>
  local d="$1" tmp="$d/$LEDGER_NAME.tmp"
  : > "$tmp"
  while IFS= read -r rel; do
    rel="${rel#./}"; [ -n "$rel" ] || continue
    printf '%s %s\n' "$(sha "$d/$rel")" "$rel" >> "$tmp"
  done < <(cd "$d" && find . -type f ! -name '.DS_Store' \
      ! -path '*/__pycache__/*' ! -name "$LEDGER_NAME*" | sort)
  mv "$tmp" "$d/$LEDGER_NAME"
}

SKILLS=()
for d in "$PKG_ROOT"/skills/*/; do
  [ -f "${d}SKILL.md" ] || continue
  SKILLS+=("$(basename "$d")")
done

install_skill_tree() {  # <skill-dir> <dest-root> — refuses on foreign files
  local master="$1" dest="$2/$(basename "$1")" rel
  sweep_tree "$master" "$dest" "$dest/$LEDGER_NAME" || return 1
  mkdir -p "$dest"
  # Per-file atomic replacement, not a tree copy: each destination file
  # lands whole or not at all (FR-007); identical files stay untouched.
  while IFS= read -r rel; do
    rel="${rel#./}"; [ -n "$rel" ] || continue
    mkdir -p "$dest/$(dirname "$rel")"
    cmp -s "$master/$rel" "$dest/$rel" \
      || atomic_put "$master/$rel" "$dest/$rel" || return 1
  done < <(cd "$master" && find . -type f ! -name '.DS_Store' \
      ! -path '*/__pycache__/*' ! -name "$LEDGER_NAME*")
  record_tree "$dest"
}

DEF_OWNERS="$(mktemp)"  # basename|owner|master-path lines (bash-3.2 safe)
trap 'rm -rf "$preflight_stage" "$DEF_OWNERS"' EXIT

# Flat agent roots are ONE namespace and the split shares archetypes
# (builder/reviewer in shape+execute+monolith, scout in intent+monolith).
# rc 0 = install (unowned); rc 3 = skip (owned, byte-identical);
# rc 4 = REFUSE (owned, bytes differ — names both owners; never a silent
# last-writer-wins).
def_dedup_gate() {  # <basename> <skill-name> <master-file>
  local base="$1" owner="$2" master="$3" line first firstpath
  line="$(awk -F'|' -v b="$base" '$1 == b {print; exit}' "$DEF_OWNERS")"
  if [ -z "$line" ]; then
    printf '%s|%s|%s\n' "$base" "$owner" "$master" >> "$DEF_OWNERS"
    return 0
  fi
  first="$(printf '%s' "$line" | awk -F'|' '{print $2}')"
  firstpath="$(printf '%s' "$line" | awk -F'|' '{print $3}')"
  [ "$first" = "$owner" ] && return 0
  cmp -s "$firstpath" "$master" && return 3
  echo "REFUSE archetype $base — $owner's brief differs from $first's ($firstpath); resolve before install" >&2
  return 4
}

# A skill's generated def set may be skipped wholesale when every brief
# it would write is already owned byte-identically by an earlier skill.
defs_all_owned() {  # <skill-dir> <skill-name>
  local dir="$1" name="$2" f base rc any_own=0
  for f in "$dir"/agents/*.md; do
    [ -e "$f" ] || continue
    base="$(basename "$f")"
    [[ "$base" == _* ]] && continue
    def_dedup_gate "$base" "$name" "$f"; rc=$?
    [ "$rc" -eq 0 ] && any_own=1
    [ "$rc" -eq 4 ] && return 4
  done
  [ "$any_own" -eq 1 ] && return 0
  return 3
}

install_command() {  # <master-file> <base> <root> — ledger-guarded copy
  local f="$1" base="$2" root="$3"
  # Second statement, deliberately: in one `local a=$b c=$a` line every
  # expansion happens BEFORE any assignment, so $root would read the
  # caller's leftover global, not this function's parameter.
  local dest="$root/$base.md" ledger="$root/$LEDGER_NAME"
  mkdir -p "$root"
  if [ -e "$dest" ] && ! cmp -s "$f" "$dest" \
     && ! ledger_entry_matches "$ledger" "$base" "$dest"; then
    echo "REFUSE $dest — foreign file (differs from master, not a prior deploy); resolve manually"
    return 1
  fi
  atomic_put "$f" "$dest" || return 1
  ledger_record "$ledger" "$base" "$f"
}

# --- preflight -------------------------------------------------------------
# Plan every destination this run may touch BEFORE the first write
# (FR-001, FR-002): tools/ownership.py classifies each candidate as
# create / update / unchanged / delete / refuse from the destination's
# provenance ledger, and generated content is rendered to scratch first
# so a generator or source failure also costs zero writes (D-002 — a
# collision in the last root must not leave the first root
# half-updated). Refuse means the ledger cannot prove the occupant is a
# prior deploy: however identical it looks, it is never adopted.
# Unplanned here: agy personas (committed regenerate-only repo
# artifacts, no destination ledger) and the opencode/droid agent roots
# (no provenance record exists yet; their deployment alignment is
# T006's) — but their renders are still validated before any write.
PREFLIGHT_FAIL=0
preflight_stage="$(mktemp -d)"

plan_tree_root() {  # <src-dir> <dest-dir> — fail the run on any refusal
  local dest="$2" out rc line
  out="$(python3 "$PKG_ROOT/tools/ownership.py" plan-tree \
      --src "$1" --dest "$dest")" && rc=0 || rc=$?
  # rc 2 is a planner validation error (missing source, corrupt ledger)
  # — a prerequisite failure, loud on stderr, fatal here either way.
  if [ "$rc" -eq 2 ]; then PREFLIGHT_FAIL=1; return 0; fi
  while IFS= read -r line; do
    case "$line" in
      refuse\ *)
        PREFLIGHT_FAIL=1
        echo "REFUSE $dest/${line#refuse } — foreign file (differs from master, not a prior deploy); resolve manually" ;;
      *)
        # --dry-run reports every decision in the planner's own
        # create/update/unchanged/delete vocabulary (FR-009)
        [ "$DRY_RUN" = 1 ] && echo "plan  ${line%% *} $dest/${line#* }" ;;
    esac
  done <<< "$out"
  return 0
}

plan_file_dest() {  # <src-file> <dest-file> [planner args...] — same contract
  local src="$1" dest="$2" out rc
  shift 2
